from app.schemas.coach import CoachChatRequest, CoachChatResponse
from app.services.career_service import CAREER_SKILLS


def generate_coach_reply(payload: CoachChatRequest) -> CoachChatResponse:
    """Provide useful, context-aware coaching without requiring an API key."""
    target = payload.target_role.strip()
    target_skills = CAREER_SKILLS.get(target)
    selected = {item.strip().casefold() for item in payload.skills if item.strip()}
    gaps = [skill for skill in (target_skills or []) if skill.casefold() not in selected]
    message = payload.message.strip()
    lower = message.casefold()

    if not target_skills:
        reply = (
            f"I can help you plan a transition towards {target}. "
            "For a more accurate skill-gap plan, first choose a supported target role "
            "in the assessment."
        )
    elif any(word in lower for word in ("roadmap", "plan", "where do i start", "start")):
        first = gaps[:2] or target_skills[:2]
        reply = (
            f"Your current goal is **{payload.goal}**, moving from {payload.current_role} "
            f"towards {target}. Start with {first[0]}"
            + (f" and {first[1]}" if len(first) > 1 else "")
            + ". Spend the first week learning the fundamentals, the second week solving "
            "small practical exercises, and the third week applying the skills in one "
            "small project. Review your progress at the end of each week."
        )
    elif any(word in lower for word in ("project", "portfolio", "build")):
        first = gaps[0] if gaps else target_skills[0]
        reply = (
            f"Build a project that demonstrates {target} skills rather than a tutorial clone. "
            f"A good starting point is a small project where you use {first}"
            + (f" alongside {gaps[1]}" if len(gaps) > 1 else "")
            + ". Define one real problem, build the smallest useful version, write a clear "
            "README, add screenshots, and explain the decisions you made."
        )
    elif any(word in lower for word in ("internship", "interview", "job", "resume", "cv")):
        reply = (
            f"For a {target} opportunity, prepare evidence in three areas: fundamentals, "
            "a project you can explain end to end, and clear communication of your decisions. "
            "Update your resume with measurable project outcomes and practise explaining "
            "one technical challenge you solved. Do not claim a skill unless you can demonstrate it."
        )
    elif any(word in lower for word in ("skill", "gap", "learn", "weak", "missing")):
        if gaps:
            reply = (
                f"Based on the skills in your assessment, your main gaps for {target} are "
                + ", ".join(gaps[:4])
                + ". Pick the first gap, learn the core concepts, then complete a small exercise "
                "that proves you can use it. Mark a skill as learned only when you can apply it "
                "without following a step-by-step tutorial."
            )
        else:
            reply = (
                f"You have selected all of the skills currently mapped to {target}. "
                "That is a useful starting signal, not proof of job readiness. Validate each "
                "skill with a project, practical exercise, or interview-style explanation."
            )
    else:
        next_step = gaps[0] if gaps else "a portfolio project"
        reply = (
            f"Considering your goal of becoming a {target}, a practical next step is "
            f"{next_step}. Keep the task small enough to finish in 30–45 minutes, then write "
            "down what you understood, what confused you, and what you will practise next. "
            "Ask me about your roadmap, skill gaps, projects, resume, or interview preparation."
        )

    reply += (
        "\n\n*Coach mode: offline.* This response uses your assessment context and built-in "
        "career guidance; it is not generated by a live AI model."
    )
    return CoachChatResponse(reply=reply)
